    private void btnHasilActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHasilActionPerformed
        if (angka.isEmpty() || pilih == 0) return;
        
        double bil1 = Double.parseDouble(angka);
        
        switch(pilih){
            case 1 :
                jumlah = bil + bil1;
                break;
            case 2 :
                jumlah = bil - bil1;
                break;
            case 3 :
                jumlah = bil * bil1;
                break;
            case 4 :
                if (bil1 == 0) {
                    tampilHasil.setText("Error"); 
                    angka = "";
                    bil = 0;
                    pilih = 0;
                    return; 
                }
                jumlah = bil / bil1;
                break;
            default :
                break;
        }
        
        angka = hapusKoma(jumlah); 
        tampilHasil.setText(angka);
        
        pilih = 0;
        bil = 0;
    }//GEN-LAST:event_btnHasilActionPerformed

