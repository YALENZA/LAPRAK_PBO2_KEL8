    private void btnMinActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMinActionPerformed
       if (angka != null && !angka.isEmpty() && !angka.equals("0")) {
            double nilai = Double.parseDouble(angka);
            nilai = nilai * -1; 
            
            angka = hapusKoma(nilai);
            tampilHasil.setText(angka);
        }
    }//GEN-LAST:event_btnMinActionPerformed
    
    private String hapusKoma(double hasil) {
        if (hasil == (long) hasil) {
            return String.format("%d", (long) hasil);
        } else {
            return String.format("%s", hasil);
        }
    }
    
